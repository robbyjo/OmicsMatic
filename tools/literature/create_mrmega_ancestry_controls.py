"""Create complete synthetic cohort files and matching prepared ancestry controls."""
import argparse,json,random
from pathlib import Path
from setup_deseq2_reference import ROOT,pin,save


def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--out',type=Path,required=True);a=p.parse_args()
    out=a.out.resolve();assert not out.exists() and out.is_relative_to(ROOT/'build/literature-review/mrmega-runtime');out.mkdir(parents=True)
    rng=random.Random(5029103);cases=[];text=[]
    for number in range(12):
        n=7+number%5;axes=1+number%4;id='ancestry-'+str(number);home=out/id;home.mkdir();variants=[]
        def variant(id,chr,pos,f=None):
            variants.append(dict(id=id,chromosome=chr,position=pos,frequencies=f if f is not None else [rng.uniform(.04,.96) for _ in range(n)]))
        variant('first-ordinal-zero',1,100)
        for row in range(36+number):variant('marker-'+str(row),1+row%3,(row//3+1)*1000000+150)
        variant('same-bin-earlier',3,19000100);variant('same-bin-later',3,19000200)
        variant('float32-lower-boundary',4,1100000,[.01]*n);variant('float32-upper-boundary',4,2100000,[.99]*n)
        variant('minor-frequency-rejected',4,3100000,[.0099]*n)
        variant('missing-in-last-cohort',4,4100000,[.3]*(n-1)+[-1])
        variant('chromosome-x',23,1100000);variant('chromosome-y',24,2100000);variant('chromosome-xy',25,3100000)
        variant('last-unread-bin',1,299000150);variant('outside-matrix-columns',1,301000150)
        variant('alias-column300',1,300000150)
        if number%2:variant('overwrites-slot-alias',2,150)
        effects=[rng.uniform(-.2,.2) for _ in range(n)];weights=[rng.uniform(2,30) for _ in range(n)]
        sample_files=[]
        for cohort in range(n):
            path=home/('cohort-'+str(cohort)+'.tsv');sample_files.append(path)
            lines=['MARKERNAME CHROMOSOME POSITION EA NEA EAF N BETA SE']
            for index,v in enumerate(variants):
                if v['frequencies'][cohort]==-1:continue
                chromosome={23:'X',24:'Y',25:'XY'}.get(v['chromosome'],str(v['chromosome']))
                lines.append(' '.join([v['id'],chromosome,str(v['position']),'A','G',format(v['frequencies'][cohort],'.17g'),str(1000+cohort*17),format(.02+index*.001+cohort*.003,'.17g'),'.12']))
            path.write_text('\n'.join(lines)+'\n',encoding='utf8',newline='\n')
        # Paths are generated by the Linux reference runner at its new case root;
        # these immutable input files contain no absolute platform-specific list.
        case=dict(id=id,cohorts=n,axes=axes,variants=variants,effects=effects,weights=weights,
            cohort_files=[path.relative_to(out).as_posix() for path in sample_files])
        save(home/'case.json',case);cases.append(case)
        text.append(f'{id} {n} {axes} {len(variants)}')
        for v in variants:text.append(' '.join([v['id'],str(v['chromosome']),str(v['position']),*[format(x,'.17g') for x in v['frequencies']]]))
        for y,w in zip(effects,weights,strict=True):text.append(format(y,'.17g')+' '+format(w,'.17g'))
    (out/'prepared-controls.txt').write_text('\n'.join(text)+'\n',encoding='utf8',newline='\n');save(out/'cases.json',cases)
    files={path.relative_to(out).as_posix():pin(path) for path in out.rglob('*') if path.is_file()}
    save(out/'COMPLETED.json',dict(status='PASS_TWELVE_SYNTHETIC_MRMEGA_ANCESTRY_CONTROL_FAMILIES_ONLY',complete_cases=12,files=files,
        source_pins={Path(__file__).relative_to(ROOT).as_posix():pin(Path(__file__))},analysis_admitted=False,implementation_credit=False,whole_goal_complete=False))
    print('Prepared12 complete synthetic cohort-file/ancestry families; no analysis executed')


if __name__=='__main__':
    if not __debug__:raise RuntimeError('Never disable complete control population checks')
    main()
