# Compare every original return/condition/RNG value. Only the known wall-clock
# header at original_returns$limma_value$expr may differ. Raw RDS files stay intact.
args <- commandArgs(TRUE)
stopifnot(length(args)==4L)
.libPaths(readLines("libraries.txt",warn=FALSE),include.site=FALSE)
locale.result <- Sys.setlocale("LC_ALL","English_United States.utf8")
stopifnot(nzchar(locale.result),all(vapply(c("LC_COLLATE","LC_CTYPE","LC_MONETARY","LC_TIME"),
  Sys.getlocale,character(1))=="English_United States.utf8"))
Sys.setlocale("LC_TIME","C");Sys.setenv(TZ="UTC")
mem.maxVSize(as.numeric(args[[4]]))
values <- lapply(args[1:2],readRDS)
headers <- character()
exact <- function(a,b)identical(a,b,num.eq=FALSE,single.NA=FALSE,
  attrib.as.set=FALSE,ignore.bytecode=FALSE,ignore.environment=FALSE,ignore.srcref=FALSE)
for (i in 1:2) {
  value <- values[[i]]
  stopifnot(identical(names(value),c("original_returns","original_conditions","RNG_before","RNG_after")),
            is.list(value$original_returns),is.list(value$original_returns$limma_value))
  text <- value$original_returns$limma_value$expr
  base <- dirname(args[[i]])
  for (name in names(value$original_returns))
    stopifnot(exact(value$original_returns[[name]],readRDS(file.path(base,"stages",paste0(name,".rds")))))
  stopifnot(exact(value$original_conditions,readRDS(file.path(base,"complete-conditions.rds"))$conditions))
  stopifnot(is.character(text),length(text)==1L,!is.na(text))
  n <- regexpr("\n",text,fixed=TRUE)[[1]]
  stopifnot(n>1L)
  header <- substr(text,1L,n)
  pattern <- paste0("^# DESeq2 script generated by iDEP on ",
    "(Mon|Tue|Wed|Thu|Fri|Sat|Sun) (Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec) ",
    "[ 0-9][0-9] [0-9]{2}:[0-9]{2}:[0-9]{2} [0-9]{4}\n$")
  stopifnot(grepl(pattern,header),!is.na(strptime(
    sub("^# DESeq2 script generated by iDEP on ","",header),
    format="%a %b %d %H:%M:%S %Y",tz="UTC")))
  headers[[i]] <- header
  value$original_returns$limma_value$expr <- paste0(
    "# DESeq2 script generated by iDEP on <TIMESTAMP>\n",substring(text,n+1L))
  values[[i]] <- value
}
same <- exact(values[[1]],values[[2]])
auxiliary <- c("caller-context.rds","namespace-before.rds","namespace-after.rds","complete-conditions.rds")
for (name in auxiliary)
  same <- same && exact(readRDS(file.path(dirname(args[[1]]),name)),
                         readRDS(file.path(dirname(args[[2]]),name)))
jsonlite::write_json(list(status=if(same)"PASS_COMPLETE_ORIGINAL_IDEP244_REPLAY"else
  "FAIL2_COMPLETE_ORIGINAL_IDEP244_REPLAY_DIFFERS",complete_values_equal=same,
  compared="Every original stage return, class, attribute, identifier, condition and complete RNG before/after",
  only_permitted_difference="Known first generated-script timestamp header at original_returns$limma_value$expr",
  original_timestamp_header=headers[[1]],replay_timestamp_header=headers[[2]],
  all_other_generated_script_bytes_compared=TRUE,
  numeric_NA_NaN_Inf_signed_zero_normalized=FALSE,raw_RDS_files_modified=FALSE),
  args[[3]],auto_unbox=TRUE,pretty=TRUE,null="null")
quit(save="no",status=if(same)0L else 2L,runLast=FALSE)
