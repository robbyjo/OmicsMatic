# Strict original returns/RNG/conditions. Only the known generated timestamp line
# and session transport identifiers receive explicit, separately recorded policies.
p <- commandArgs(TRUE)
stopifnot(length(p)==5L)
.libPaths(readLines(p[[1]],warn=FALSE),include.site=FALSE)
left <- p[[2]];right <- p[[3]];destination <- p[[4]];mode <- p[[5]]
stopifnot(mode%in%c("success","original-error-signature-only"))
same <- function(a,b)identical(a,b,num.eq=FALSE,single.NA=FALSE,attrib.as.set=FALSE,
  ignore.bytecode=FALSE,ignore.environment=FALSE,ignore.srcref=FALSE)
read <- function(root,name)readRDS(file.path(root,"original",name))
a <- read(left,if(mode=="success")"complete-original-returns.rds"else"complete-failed-returns.rds")
b <- read(right,"complete-original-returns.rds")
normalize.timestamp <- function(value) {
  if (!"limma_value"%in%names(value$original_returns))return(value)
  text <- value$original_returns$limma_value$expr
  stopifnot(is.character(text),length(text)==1L)
  first <- strsplit(text,"\n",fixed=TRUE)[[1]][[1]]
  pattern <- "^# DESeq2 script generated by iDEP on (Mon|Tue|Wed|Thu|Fri|Sat|Sun) (Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec) [ 0-9][0-9] [0-9]{2}:[0-9]{2}:[0-9]{2} [0-9]{4}$"
  stopifnot(grepl(pattern,first))
  value$original_returns$limma_value$expr <- paste0("# DESeq2 script generated by iDEP on <recorded caller time>",
    substring(text,nchar(first)+1L))
  value
}
aa <- normalize.timestamp(a);bb <- normalize.timestamp(b)
stopifnot(same(aa$original_returns,bb$original_returns),same(a$RNG_before,b$RNG_before),same(a$RNG_after,b$RNG_after))
stages <- names(a$original_returns)
stopifnot(identical(stages,names(b$original_returns)))
for (name in stages) {
  stopifnot(same(read(left,paste0("stages/",name,".rds")),a$original_returns[[name]]),
            same(read(right,paste0("stages/",name,".rds")),b$original_returns[[name]]))
}
for (name in c("namespace-before.rds","namespace-after.rds","caller-context.rds"))
  stopifnot(same(read(left,name),read(right,name)))
sa <- read(left,"session-context.rds");sb <- read(right,"session-context.rds")
stopifnot(identical(names(sa),names(sb)),identical(names(sa),c("session_class","default_domain_class","genuine_session","token")))
stopifnot(same(sa[names(sa)!="token"],sb[names(sb)!="token"]),isTRUE(sa$genuine_session),isTRUE(sb$genuine_session),
  is.character(sa$token),length(sa$token)==1L,nzchar(sa$token),is.character(sb$token),length(sb$token)==1L,nzchar(sb$token))
condition.objects.equal <- FALSE;error.signature.equal <- NULL
if (mode=="success") {
  stopifnot(same(aa,bb),same(read(left,"complete-conditions.rds"),read(right,"complete-conditions.rds")))
  condition.objects.equal <- TRUE
} else {
  # Failed-call stacks contain different surrounding caller expressions. Both
  # full raw stacks remain saved. This mode claims ONLY the named error fields,
  # full partial original stage values and complete before/after RNG identity.
  ac <- read(left,"complete-conditions.rds");bc <- read(right,"complete-conditions.rds")
  stopifnot(!is.null(ac$error),!is.null(bc$error),length(ac$conditions)==length(bc$conditions))
  signature <- function(c)list(class=class(c),message=conditionMessage(c),call=conditionCall(c))
  stopifnot(same(signature(ac$error),signature(bc$error)))
  for (i in seq_along(ac$conditions)) {
    x <- ac$conditions[[i]];y <- bc$conditions[[i]]
    stopifnot(same(x[c("kind","phase","class","message","call")],y[c("kind","phase","class","message","call")]),
              same(signature(x$condition),signature(y$condition)))
  }
  error.signature.equal <- TRUE
}
jsonlite::write_json(list(status="PASS_DECLARED_ORIGINAL_SHINY_COMPARISON_SCOPE",mode=mode,
  complete_original_stage_values_equal=TRUE,complete_RNG_before_after_equal=TRUE,
  complete_original_condition_objects_equal=condition.objects.equal,primary_original_error_signature_equal=error.signature.equal,
  full_failure_stack_comparison_claimed=FALSE,complete_caller_context_equal=TRUE,
  full_raw_original_RDS_preserved=TRUE,namespace_audits_equal=TRUE,
  timestamp_policy="Only validated first generated-script timestamp line; raw scripts unchanged",
  session_identifier_policy="Only session token differs; both exact original session classes/default domains/genuine flags required",
  catalog_credit_added=0,whole_tool_qualified=FALSE),destination,pretty=TRUE,auto_unbox=TRUE,null="null")
