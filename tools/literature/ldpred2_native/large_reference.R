# Actual original sparse LDpred2 numerical controls at HapMap3-sized dimension.
args <- commandArgs(TRUE)
stopifnot(length(args)==1L,!dir.exists(args[1]))
dir.create(args[1]);out <- normalizePath(args[1],mustWork=TRUE)
stopifnot(as.character(packageVersion("bigsnpr"))=="1.12.2")
library(bigsnpr)
options(digits=17,scipen=999)
m <- 1100000L; columns <- seq_len(m)
partner <- ifelse(columns %% 2L==1L,columns+1L,columns-1L)
corr <- Matrix::sparseMatrix(i=c(columns,partner),j=rep(columns,2L),x=c(rep(1,m),rep(0.25,m)),dims=c(m,m))
writeBin(corr@p,file.path(out,"ld-pointers.i32"),size=4,endian="little")
writeBin(corr@i,file.path(out,"ld-rows.i32"),size=4,endian="little")
writeBin(corr@x,file.path(out,"ld-values.f64"),size=8,endian="little")
ld <- bigsparser::as_SFBM(corr,backingfile=file.path(out,"private-original-ld"))
df <- data.frame(beta=rep(c(0.2,0.1),m/2L),beta_se=rep(c(0.01,0.015),m/2L),n_eff=rep(c(10000,18000),m/2L))
for(name in names(df))writeBin(df[[name]],file.path(out,paste0(name,".f64")),size=8,endian="little")
scale <- with(df,sqrt(n_eff*beta_se^2+beta^2))
inf <- snp_ldpred2_inf(ld,df,h2=0.3)
stopifnot(length(inf)==m,all(is.finite(inf)))
writeBin(inf,file.path(out,"original-inf-allele.f64"),size=8,endian="little")
RNGkind("L'Ecuyer-CMRG","Inversion","Rejection");set.seed(32768)
writeLines(as.character(.Random.seed),file.path(out,"seed-before.txt"))
core <- bigsnpr:::ldpred2_gibbs_one(ld,df$beta/scale,df$n_eff,seq_len(m)-1L,0.3,1,FALSE,1L,3L)
stopifnot(length(core)==m,all(is.finite(core)))
writeBin(core*scale,file.path(out,"original-grid-allele.f64"),size=8,endian="little")
writeLines(as.character(.Random.seed),file.path(out,"seed-after.txt"))
writeLines(capture.output(sessionInfo()),file.path(out,"sessionInfo.txt"))
writeLines(c("PASS_ORIGINAL_LDPRED2_1122_1100000_VARIANTS",paste0("variants=",m),paste0("stored_ld_entries=",length(corr@x)),"grid_burn_in=1","grid_iterations=3","ld_is_synthetic_pair_blocks=TRUE","whole_paper_or_LD_resource_reproduced=FALSE"),file.path(out,"COMPLETED.txt"))
