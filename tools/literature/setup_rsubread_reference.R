# Install only the declared local archive into a NEW private library; no network.
args <- commandArgs(trailingOnly=TRUE)
stopifnot(length(args)==4L, getRversion()=="4.6.1")
lib <- args[[1L]]; out <- args[[2L]]; archive <- args[[3L]]; source <- args[[4L]]
stopifnot(!dir.exists(lib), file.exists(archive), file.exists(source))
dir.create(lib)
.libPaths(c(lib,.Library))
utils::install.packages(archive,lib=lib,repos=NULL,type="win.binary")
ns <- loadNamespace("Rsubread",lib.loc=lib)
stopifnot(as.character(utils::packageVersion("Rsubread",lib.loc=lib))=="2.26.0")
reference <- new.env(parent=baseenv())
sys.source(source,envir=reference)
original <- get("featureCounts",envir=ns,inherits=FALSE)
expected <- get("featureCounts",envir=reference,inherits=FALSE)
stopifnot(identical(formals(original),formals(expected)),identical(body(original),body(expected)))
saveRDS(formals(original),file.path(out,"featureCounts-formals.rds"),version=3L)
saveRDS(body(original),file.path(out,"featureCounts-body.rds"),version=3L)
dput(formals(original),file=file.path(out,"featureCounts-formals.R"))
dput(body(original),file=file.path(out,"featureCounts-body.R"))
writeLines(capture.output(utils::sessionInfo()),file.path(out,"sessionInfo.txt"))
packages <- sort(loadedNamespaces())
write.table(data.frame(package=packages,version=vapply(packages,function(p)as.character(utils::packageVersion(p)),""),path=vapply(packages,function(p)normalizePath(find.package(p,lib.loc=.libPaths()),winslash="/",mustWork=TRUE),"")),file=file.path(out,"namespaces.tsv"),sep="\t",quote=TRUE,row.names=FALSE,na="NA")
dlls <- getLoadedDLLs()
write.table(data.frame(name=names(dlls),path=vapply(dlls,function(x)x[["path"]],"")),file=file.path(out,"loaded-dlls.tsv"),sep="\t",quote=TRUE,row.names=FALSE)
writeLines(c("status\tdetail","INSTALLED_ORIGINAL_RSUBREAD_REFERENCE_ONLY\tOriginal2.26.0 namespace featureCounts formals/body equal the unmodified official source; no analysis run"),file.path(out,"R-status.tsv"))
