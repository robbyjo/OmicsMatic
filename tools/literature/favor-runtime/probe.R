library(gdsfmt)
library(SeqArray)
library(readr)
library(jsonlite)
library(digest)
library(GenomeInfoDbData)
args <- commandArgs(TRUE)
input <- file.path(args[1],"probe.csv")
writeLines(c("number,label","1,雪","2,quoted"),input,useBytes=TRUE)
x <- read_csv(input,show_col_types=FALSE)
stopifnot(identical(x$number,c(1,2)),identical(x$label,c("雪","quoted")))
g <- createfn.gds(file.path(args[1],"probe.gds"))
node <- add.gdsn(g$root,"logical",val=c(TRUE,FALSE,NA),compress="LZMA_ra",closezip=TRUE)
stopifnot(identical(read.gdsn(node),c(TRUE,FALSE,NA)))
closefn.gds(g)
versions <- lapply(c("gdsfmt","SeqArray","readr","jsonlite","digest","GenomeInfoDbData"),function(name)list(name=name,version=as.character(packageVersion(name)),path=find.package(name)))
maps <- readLines("/proc/self/maps",warn=FALSE)
paths <- sub("^[^/]*", "", maps[grepl("/",maps,fixed=TRUE)])
write_json(list(status="loaded-and-small-IO-smoke-only",R=R.version.string,R_home=R.home(),loader_path=Sys.getenv("LD_LIBRARY_PATH"),tools=as.list(Sys.which(c("mkdir","sh"))),library_paths=I(.libPaths()),packages=versions,dll_paths=I(vapply(getLoadedDLLs(),function(d)d[["path"]],character(1))),mapped_paths=I(sort(unique(paths))),host=as.list(Sys.info()[c("sysname","release","machine")])),args[2],auto_unbox=TRUE,pretty=TRUE)
