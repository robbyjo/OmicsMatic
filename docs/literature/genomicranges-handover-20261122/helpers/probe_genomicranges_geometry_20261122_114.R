args<-commandArgs(TRUE)
out<-args[[1]];dir.create(out,recursive=TRUE,showWarnings=FALSE)
libs<-args[-1L];.libPaths(c(libs,.Library))
suppressPackageStartupMessages(library(GenomicRanges))
stopifnot(as.character(packageVersion("GenomicRanges"))=="1.64.0")
metadata<-lapply(loadedNamespaces(),function(pkg){d<-packageDescription(pkg);list(package=pkg,version=d$Version,Built=d$Built,path=find.package(pkg))})
saveRDS(list(R=R.version,packages=metadata,libpaths=.libPaths(),session=sessionInfo()),file.path(out,"RUNTIME.rds"))
writeLines(c(R.version.string,vapply(metadata,function(x)paste(x$package,x$version,x$path,sep="\t"),"")),file.path(out,"RUNTIME.txt"),useBytes=TRUE)
si<-Seqinfo("chr1",1000L,FALSE,"artificial")
query<-GRanges("chr1",IRanges(100L,100L),strand="+",seqinfo=si)
subject<-GRanges("chr1",IRanges(c(90L,110L),width=1L),strand="+",seqinfo=si)
arbitrary<-nearest(query,subject,select="arbitrary")
all<-nearest(query,subject,select="all")
distance<-distanceToNearest(query,subject,select="all")
write.table(as.data.frame(distance),file.path(out,"EQUAL-DISTANCE-ALL.tsv"),sep="\t",quote=FALSE,row.names=FALSE)
saveRDS(list(query=query,subject=subject,arbitrary=arbitrary,all=all,distance=distance),file.path(out,"EQUAL-DISTANCE-ALL.rds"))
cat("NEAREST_ARBITRARY",arbitrary,"\n");cat("NEAREST_ALL_SUBJECTS",subjectHits(all),"\n")
source_function<-get("get_out_of_bound_index",asNamespace("GenomicRanges"))
for(name in c(".nearest",".compute_promoter_ranges",".GenomicRanges_promoters","get_out_of_bound_index")){
 fn<-get(name,asNamespace("GenomicRanges"));writeLines(c(deparse(formals(fn),width.cutoff=500L),deparse(body(fn),width.cutoff=500L)),file.path(out,paste0(sub("^\\.","internal-",name),".txt")),useBytes=TRUE)
}
g<-GRanges(rep("chr1",3),IRanges(c(1L,100L,999L),width=1L),strand=c("+","*","-"),seqinfo=si)
conditions<-character();p<-withCallingHandlers(promoters(g,upstream=5000L,downstream=5000L),warning=function(w){conditions<<-c(conditions,conditionMessage(w));invokeRestart("muffleWarning")})
write.table(as.data.frame(p),file.path(out,"PROMOTERS.tsv"),sep="\t",quote=FALSE,row.names=FALSE);saveRDS(list(input=g,result=p,out_of_bound=source_function(p),conditions=conditions),file.path(out,"PROMOTERS.rds"));writeLines(conditions,file.path(out,"CONDITIONS.txt"),useBytes=TRUE)
cat("PROMOTER_BOUNDS",source_function(p),"\n")
for(circular in list(TRUE,FALSE,NA))for(length in list(0L,1000L,NA_integer_)){
 seqinfo<-Seqinfo("chr1",seqlengths=length,isCircular=circular,genome="artificial")
 value<-suppressWarnings(GRanges("chr1",IRanges(start=c(-2L,0L,1001L),width=c(1L,0L,0L)),strand="*",seqinfo=seqinfo))
 cat("BOUNDS",as.character(circular),as.character(length),paste(source_function(value),collapse=","),"\n")
}
saveRDS(list(status="ORIGINAL164_SOURCE_FEASIBILITY_ONLY",original_164=TRUE,new_catalog_credit=0),file.path(out,"STATUS.rds"))
